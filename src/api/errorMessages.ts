/** 사용자에게 보여 줄 에러 문구 */
export function toUserMessage(code: string, status: number, serverMessage: string | undefined): string {
  const mapped = USER_MESSAGES[code]
  if (mapped) return mapped
  // 표에 없는 5xx, 내부 정합성 오류(지갑·충전·결제 금액 불일치 등)는 내부 문구를 숨긴다
  if (status >= 500) return RETRY
  if (status === 401) return USER_MESSAGES.COMMON002
  if (status === 403) return NOT_ALLOWED
  if (/^(WALLET|CHARGE|PAYMENT)/.test(code)) return RETRY
  return serverMessage || '요청을 처리하지 못했어요. 잠시 후 다시 시도해 주세요.'
}
