export type ErrorCode = keyof typeof ERROR_TABLE;

export class MockError extends Error {
  status: number;
  code: string;

  constructor(status: number, code: string, message: string) {
    super(message);
    this.status = status;
    this.code = code;
  }
}

/** 에러 코드에 맞는 MockError 를 던진다 */
export function fail(code: ErrorCode): never {
  const [status, message] = (ERROR_TABLE[code] as readonly [number, string] | undefined) ?? [
    400,
    '요청을 처리하지 못했어요.',
  ];
  throw new MockError(status, code, message);
}
